// VM-style: Lambda Cloud
// ---------------------------------------------------------------------------

export function gpuKeyPaths(rootDir, label) {
  const dir = path.join(byocDir(rootDir), 'gpu-keys');
  return { dir, privateKeyPath: path.join(dir, label), publicKeyPath: path.join(dir, `${label}.pub`) };
}

/** A dedicated keypair per provider, separate from the user's personal keys — freely referenceable, freely revocable. */
export async function ensureGpuKeypair(rootDir, label) {
  const { dir, privateKeyPath, publicKeyPath } = gpuKeyPaths(rootDir, label);
  fs.mkdirSync(dir, { recursive: true });
  if (!fs.existsSync(privateKeyPath)) {
    await new Promise((resolve, reject) => {
      let child;
      try {
        child = spawn('ssh-keygen', ['-t', 'ed25519', '-N', '', '-C', `sovereignai-byoc-${label}`, '-f', privateKeyPath], { windowsHide: true });
      } catch (err) {
        reject(new GpuProvisionError(`Could not start ssh-keygen: ${err.message}`));
        return;
      }
      child.once('error', (err) => reject(new GpuProvisionError(`Could not run ssh-keygen: ${err.message}`)));
      child.once('close', (code) => (code === 0 ? resolve() : reject(new GpuProvisionError(`ssh-keygen exited ${code}`))));
    });
    try {
      fs.chmodSync(privateKeyPath, 0o600);
    } catch (err) {
      if (err.code !== 'EPERM' && err.code !== 'ENOSYS') throw err;
    }
  }
  const publicKey = fs.readFileSync(publicKeyPath, 'utf8').trim();
  return { privateKeyPath, publicKey };
}

async function waitForSsh({ target, keyPath, knownHostsFile, timeoutMs, sleep, log }) {
  const deadline = Date.now() + timeoutMs;
  let lastError = 'not yet reachable';
  for (;;) {
    try {
      const runner = createSshRunner({ target, keyPath, knownHostsFile, strictHostKey: false });
      const result = await runner.exec('true', { timeoutMs: 8000 });
      if (result.code === 0) return;
      lastError = `ssh exited ${result.code}`;
    } catch (err) {
      lastError = err.message;
    }
    if (Date.now() >= deadline) throw new GpuProvisionError(`Could not reach ${target} over SSH: ${lastError}`);
    log(`  waiting for SSH to accept the key… (${lastError})`);
    await sleep(PROVISION_POLL_MS);
  }
}

/**
 * Provision a VM-style GPU instance and wait until it accepts our dedicated
 * key over SSH. Returns exactly what `createSshRunner` + connector.js
 * `deploy` need — the caller reuses that existing pipeline unchanged.
 */
export async function provisionVm({
  rootDir,
  providerId,
  apiKey,
  gpuTypeId,
  name,
  region,
  log = noop,
  sleep = defaultSleep,
  provisionTimeoutMs = DEFAULT_PROVISION_TIMEOUT_MS,
  readyTimeoutMs = DEFAULT_READY_TIMEOUT_MS,
} = {}) {
  const provider = getGpuProvider(providerId);
  if (provider.computeStyle !== 'vm') throw new GpuProvisionError(`${provider.label} is not a VM-style provider`);
  if (typeof provider.ensureSshKey !== 'function') throw new GpuProvisionError(`${provider.label} does not support SSH key registration`);

  log(`• Preparing a dedicated SSH key for ${provider.label}…`);
  const { privateKeyPath, publicKey } = await ensureGpuKeypair(rootDir, `${providerId}-default`);
  const { ref: sshKeyRef } = await provider.ensureSshKey({ apiKey, publicKey, label: `sovereignai-${providerId}-default` });

  log(`• Requesting a GPU instance from ${provider.label}…`);
  const { instanceId } = await provider.provision({ apiKey, gpuTypeId, name, sshKeyRef, region });
  log(`  requested: instance ${instanceId} — if anything below fails, terminate it in the ${provider.label} console so it doesn't keep billing.`);

  const running = await pollUntilRunning(provider, { apiKey, instanceId, timeoutMs: provisionTimeoutMs, sleep, log });
  if (!running.host) {
    throw new GpuProvisionError(`${provider.label} marked instance ${instanceId} running but did not report an address. It is still running and billing — terminate it in the ${provider.label} console if you don't intend to retry.`);
  }

  const sshUser = running.sshUser || 'root';
  const target = `${sshUser}@${running.host}`;
  log(`  reachable at ${target} — waiting for SSH to accept the key…`);
  const knownHostsFile = path.join(byocDir(rootDir), 'known_hosts');
  await waitForSsh({ target, keyPath: privateKeyPath, knownHostsFile, timeoutMs: readyTimeoutMs, sleep, log });

  return {
    computeStyle: 'vm',
    provider: { name: provider.id, instanceId, gpuTypeId },
    target,
    sshPort: 22,
    keyPath: privateKeyPath,
  };
}
